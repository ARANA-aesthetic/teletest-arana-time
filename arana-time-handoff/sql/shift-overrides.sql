-- ARANA TIME — เข้างานพิเศษเฉพาะวัน (เช่น ไฟดับ/ซ่อมสายไฟ อนุมัติให้เข้างานสายกว่าปกติได้)
-- รันทั้งไฟล์นี้ใน Supabase SQL Editor ครั้งเดียว (ปลอดภัย รันซ้ำได้ — add column if not exists)
--
-- ที่มา: เคสจริง การไฟฟ้าตัดไฟซ่อมสายไฟ อนุมัติให้พนักงานเข้างานประมาณ 14:30 แทนเวลาเข้ากะปกติ
-- ต้องการวิธีปรับ "เวลาเข้างานที่ถือว่าไม่สาย" เฉพาะวันนั้น (จะทั้งบริษัท หรือเฉพาะสาขา) โดยไม่ต้องไป
-- แก้ไขเวลากะ (shift_start) ถาวรของพนักงานแต่ละคนทีละคน
--
-- กลไก: เพิ่มคอลัมน์ shift_overrides (jsonb array) ใน settings เก็บ [{id, date, branchId(null=ทุกสาขา),
-- newShiftStart, reason}] จัดการได้จากหน้าตั้งค่า → เกณฑ์สาย/ขาด → "เข้างานพิเศษเฉพาะวัน" ฟังก์ชัน
-- shiftLateMinutes() จะเช็กว่าวันนี้มีประกาศเข้างานพิเศษที่ตรงกับสาขาของพนักงานหรือไม่ ถ้ามีจะใช้เวลานั้น
-- แทนเวลาเข้ากะปกติ (ผลคือ maSAY จะเริ่มนับจากเวลาใหม่แทน)

alter table settings add column if not exists shift_overrides jsonb default '[]'::jsonb;
