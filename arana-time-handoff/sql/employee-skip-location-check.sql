-- ARANA TIME — ธง "สแกนนอกพื้นที่ได้" รายบุคคล (ข้ามการเช็กพิกัด/GPS ตอนสแกนเข้า-ออกงาน)
-- ออมรันเองใน Supabase SQL editor ของโปรเจกต์ ARANA TIME (Claude ไม่ได้รันให้ ตามกฎที่ตั้งไว้) — เก็บไฟล์นี้ไว้เป็นบันทึกในโปรเจกต์
--
-- ที่มา: 28 ต.ค. 69 พนักงานตำแหน่งแอดมินกะกลางคืนทำงานที่บ้านตั้งแต่ 24 ต.ค. สแกนเข้างานไม่ได้เพราะอยู่นอกรัศมีสาขา
-- เจ้าของต้องการให้ "ตำแหน่งนี้" สแกนนอกพื้นที่ได้ถาวร (จะมาเรียนงานที่ออฟฟิศแค่ราว 14 วัน) และยังต้องนับเวลาสายตามปกติ
-- จึงใช้คำขอ "ทำงานนอกสถานที่" ไม่ได้ เพราะคำขอนั้นไม่คิดสาย
--
-- แก้โดยเพิ่มคอลัมน์ boolean skip_location_check ในตาราง employees (ค่าเริ่มต้น false = เช็กพิกัดตามปกติเหมือนเดิมทุกคน)
-- ฝั่งแอป: หน้าแก้ไขพนักงานมีช่องติ๊ก "สแกนนอกพื้นที่ได้ (ทำงานที่บ้าน)" — ถ้าติ๊ก ปุ่มสแกนจะข้าม GPS/พิกัดของคนนั้นคนเดียว
-- แต่ยังยืนยันใบหน้าและนับสายตามเวลาเข้ากะปกติ ไม่กระทบพนักงานคนอื่น
--
-- FK/RLS: เป็นแค่คอลัมน์เพิ่ม ไม่มี FK ใหม่ ตารางยังใช้นโยบาย RLS เปิดเดิม
alter table employees add column if not exists skip_location_check boolean not null default false;
