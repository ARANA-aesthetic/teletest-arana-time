-- รันทั้งไฟล์นี้ใน Supabase SQL Editor ครั้งเดียว (ปลอดภัย รันซ้ำได้ — add column if not exists)
--
-- ที่มา: เดิมมี weekly_off_days ระดับ "สาขา" อยู่แล้ว (วันหยุดทั้งสาขา) แต่กรณีนี้เป็นวันหยุดเฉพาะพนักงาน
-- บางคนเท่านั้น (เช่น ตำแหน่งที่ไม่ต้องเข้าวันอาทิตย์ ในขณะที่สาขายังเปิดปกติ คนอื่นยังต้องมา) จึงต้องแยก
-- เป็นคอลัมน์ใหม่ระดับพนักงานแทน ไม่ใช้ร่วมกับของสาขา
--
-- กลไก: คอลัมน์ weekly_off_days (int[], 0=อาทิตย์...6=เสาร์) ตั้งได้จากหน้าแก้ไขพนักงาน (ตั้งค่า → พนักงาน
-- → แก้ไข) พนักงานที่ตรงวันหยุดของตัวเองจะไม่ถูกนับเป็น "ขาดงาน" ทั้งในหน้าภาพรวม (ภาพรวม/สรุปรายพนักงาน)
-- และหน้ารายงาน (Reports) แม้ไม่มีการสแกนเข้างานวันนั้น — ไม่มีการแจ้งเตือน Telegram ใดๆ เกี่ยวกับ "ขาดงาน"
-- อยู่แล้วในระบบ (ฟังก์ชัน cron ที่มีอยู่ไม่ได้แจ้งชื่อคนขาดงาน) จึงไม่ต้องแก้ไขฝั่ง SQL cron functions

alter table employees add column if not exists weekly_off_days int[] default '{}';
